"""Fresh proof positives and rehashed semantic forgeries (no accepted file edits)."""
import copy
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import numpy as np
from engine.jrc import ROOT, JrcDataset, load_jrc
from engine.jrc_codec import encode_jrc_store
from engine import jrc_proof as proof
from engine.source import canonical_bytes, object_hash

SCRATCH = ROOT / 'data/experimental/jrc-engine/proof-tests'


def rehash_artifact(artifact):
    for plot in artifact['plots']:
        receipt = plot['receipt']
        receipt['receipt_sha256'] = object_hash({k: v for k, v in receipt.items() if k != 'receipt_sha256'})
    artifact['content_sha256'] = object_hash({k: v for k, v in artifact.items() if k != 'content_sha256'})
    return artifact


class JrcProofTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        SCRATCH.mkdir(parents=True, exist_ok=True)
        cls.temp = tempfile.TemporaryDirectory(dir=SCRATCH)
        cls.root = Path(cls.temp.name)
        cls.addClassCleanup(cls.temp.cleanup)
        cls.canonical = json.loads((ROOT / 'artifacts/jrc-baseline-v1.json').read_text())
        cls.controls = []
        cls.store = ROOT / cls.canonical['store']['path']
        # Fresh controls generated by current code; rejection of stale artifacts
        # cannot substitute for acceptance of current evidence.
        cls.fresh = proof.export_jrc(output=cls.root / 'fresh.json', store=cls.store,
                                     benchmark=cls.canonical['benchmark'])
        cls.metric_free = proof.export_jrc(output=cls.root / 'metric-free.json', store=cls.store)

    @classmethod
    def tearDownClass(cls):
        result = {'canonical_content_sha256': cls.canonical['content_sha256'],
                  'benchmark_run': cls.canonical['benchmark']['archive']['run_id'],
                  'fresh_control_matches_canonical': cls.fresh == cls.canonical,
                  'controls': cls.controls,
                  'all_expected_decisions': all(c['result']['valid'] is c['expected_valid'] for c in cls.controls)}
        path = ROOT / 'data/experimental/jrc-engine' / ('proof-controls-'+object_hash(result)+'.json')
        path.write_bytes(canonical_bytes(result))

    def check(self, value, name):
        path = self.root / (name+'.json')
        path.write_bytes(canonical_bytes(rehash_artifact(value)))
        result = proof.verify_jrc_artifact(path)
        self.controls.append({'name': name, 'expected_valid': False, 'result': result})
        return result

    def test_fresh_measured_and_metric_free_positive_controls(self):
        measured = proof.verify_jrc_artifact(self.root / 'fresh.json')
        self.controls.append({'name': 'fresh-measured-positive', 'expected_valid': True, 'result': measured})
        self.assertTrue(measured['valid'], measured)
        self.assertTrue(measured['benchmark_bound'])
        metric_free = proof.verify_jrc_artifact(self.root / 'metric-free.json')
        self.controls.append({'name': 'fresh-metric-free-positive', 'expected_valid': True, 'result': metric_free})
        self.assertTrue(metric_free['valid'], metric_free)
        self.assertFalse(metric_free['benchmark_bound'])
        self.assertEqual(measured['full_pixel_count'], 6_684_255)
        self.assertEqual(self.fresh, self.canonical)

    def test_rehashed_summary_receipt_evidence_geometry_and_class_semantics(self):
        edits = [
            ('summary', lambda x: x['summary'].update(selected_cell_count_sum=1), 'summary'),
            ('receipt-version', lambda x: x['plots'][0]['receipt'].update(query_version='wrong.v99'), 'receipt'),
            ('receipt-year', lambda x: x['plots'][0]['receipt'].update(reference_year=2099), 'receipt'),
            ('receipt-source', lambda x: x['plots'][0]['receipt'].update(dataset_sha256='0'*64), 'receipt'),
            ('receipt-fidelity', lambda x: x['plots'][0]['receipt'].update(
                full_chip={**x['plots'][0]['receipt']['full_chip'], 'mask_equal': False}), 'receipt'),
            ('evidence', lambda x: x['plots'][0]['evidence']['cells'][0].update(valid=False), 'evidence'),
            ('geometry', lambda x: x['plots'][0].update(geometry_sha256='0'*64), 'geometry_sha256'),
            ('label', lambda x: x['dataset']['classes'].update({'0': 'Unknown'}), 'dataset'),
            ('plot-result', lambda x: x['plots'][1]['compact_result']['class_counts'].update({'1': 1}), 'compact_result'),
            ('comparison', lambda x: x['plots'][0]['comparison'].update(equal=False), 'comparison'),
        ]
        for name, edit, failure in edits:
            forged = copy.deepcopy(self.metric_free)
            edit(forged)
            result = self.check(forged, name)
            with self.subTest(case=name):
                self.assertFalse(result['valid'], result)
                self.assertIn(failure, result['failures'][0])

    def test_offplot_raw_and_mask_mutations_rejected_before_benchmark(self):
        source = load_jrc()
        selected = {(cell['row'], cell['col']) for plot in self.metric_free['plots'] for cell in plot['evidence']['cells']}
        point = next((r, c) for r in range(source.values.shape[0]) for c in range(source.values.shape[1]) if (r, c) not in selected)
        for field in ('raw', 'mask'):
            bad = JrcDataset(source.values.copy(), source.mask.copy(), source.metadata)
            if field == 'raw': bad.values[point] ^= 1
            else: bad.mask[point] = not bad.mask[point]
            store = self.root / ('offplot-'+field)
            encode_jrc_store(bad, store, 'binary_packed_zstd3', 1024)
            altered = copy.deepcopy(self.metric_free)
            actual_info = proof.info_for(store, ROOT)
            altered['store'] = actual_info
            for plot in altered['plots']: plot['receipt']['store'] = actual_info
            # All actual plot outputs remain unchanged; store hashes and receipt
            # hashes are refreshed; claimed full-chip fidelity remains true.
            result = self.check(altered, 'offplot-'+field)
            with self.subTest(field=field):
                self.assertFalse(result['valid'], result)
                self.assertIn('full-chip raw' if field == 'raw' else 'full-chip mask', result['failures'][0])
                with self.assertRaisesRegex(ValueError, 'full-chip'):
                    proof.export_jrc(store=store)

    def test_benchmark_input_identity_and_archive_bindings(self):
        for name, edit, expected in [
            ('cohort', lambda b: b['identity'].update(queries_sha256='0'*64), 'identity'),
            ('vintage', lambda b: b['identity']['source_metadata'].update(version='v3'), 'identity'),
            ('source-bytes', lambda b: b['baseline'].update(total_bytes=1), 'archive'),
            ('wrong-winner', lambda b: b['smallest_encoded'].update(total_bytes=1), 'archive'),
        ]:
            forged = copy.deepcopy(self.fresh)
            edit(forged['benchmark'])
            result = self.check(forged, name)
            with self.subTest(name=name):
                self.assertFalse(result['valid'], result)
                self.assertIn(expected, result['failures'][0])

    def test_even_self_consistent_forged_archive_cannot_fake_actual_storage(self):
        forged = copy.deepcopy(self.fresh)
        benchmark = forged['benchmark']
        benchmark['baseline']['total_bytes'] = 1
        body = {k: v for k, v in benchmark.items() if k != 'archive'}
        run = 'run-'+object_hash(body)
        relative = f"artifacts/jrc-stores/{benchmark['experiment_id']}/{run}.json"
        benchmark['archive'] = {'run_id': run, 'path': relative}
        for plot in forged['plots']: plot['receipt']['benchmark_run'] = run
        real_read = proof.read_json
        # Simulate an attacker supplying an equally forged archive without
        # writing into an experiment directory or altering any prior evidence.
        def read(path, *args, **kwargs):
            if Path(path) == ROOT / relative: return copy.deepcopy(body)
            return real_read(path, *args, **kwargs)
        with patch.object(proof, 'read_json', side_effect=read):
            result = self.check(forged, 'self-consistent-false-bytes')
        self.assertFalse(result['valid'], result)
        self.assertIn('baseline accounting', result['failures'][0])


if __name__ == '__main__': unittest.main()
